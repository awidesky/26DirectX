#pragma once
#include <vector>
#include <set>
#include <utility>
#include <algorithm>

/*
 * =================================================================================
 * [강의 노트: Physics 싱글톤 시스템 및 글로벌 충돌 관제탑의 설계]
 * =================================================================================
 * 1. 본 클래스의 역할
 * - 게임 월드 전체의 물리 연산 및 충돌 판단을 총괄하는 중앙 관제탑(Manager)임.
 * - 개별 컴포넌트(BoxCollider)들이 생성/소멸 시 보내는 신호를 수집하여 통합 관리함.
 * - 매 프레임 모든 콜라이더를 전수 조사하고, 유니티 방식의 3단계 이벤트(Enter/Stay/Exit)를
 * 정확히 계산하여 해당 오브젝트들에게 역으로 이벤트를 라우팅(전파)하는 핵심 역할을 수행함.
 *
 * 2. 싱글톤(Singleton) 패턴의 당위성과 엄격한 메모리 통제
 * - 물리 세계는 게임 내에서 '단 하나'만 존재해야 하며, 누구나 쉽게 접근할 수 있어야 함.
 * - `GetInstance()`를 통해 단 하나의 정적 인스턴스(static Physics instance)만 생성되도록 보장함.
 * - 복사 생성자 및 대입 연산자를 `delete` 처리하여 복사본이 생성되는 버그를 원천 차단함.
 * =================================================================================
 */

 // 전방 선언(Forward Declaration):
 // 헤더 인클루드 꼬임(순환 참조)을 막기 위해 클래스의 명칭만 컴파일러에게 미리 알려줌.
class BoxCollider;
class GameObject;

class Physics
{
private:
    // -------------------------------------------------------------------------
    // [내부 데이터 풀 (Data Pool)]
    // -------------------------------------------------------------------------

    // 현재 게임 월드에 활성화되어 충돌 검사를 받아야 하는 모든 BoxCollider들의 주소 목록
    std::vector<BoxCollider*> colliders;

    // [중요] '지난 프레임'에 서로 충돌 중이었던 오브젝트 쌍(Pair)들의 고유 집합
    // - Enter/Stay/Exit 상태 분기를 판정하기 위한 '거울 데이터' 역할을 수행함.
    // - 중복을 허용하지 않고 정렬 상태를 유지하는 `std::set`을 활용함.
    std::set<std::pair<GameObject*, GameObject*>> currentPairs;

    // -------------------------------------------------------------------------
    // [접근 제한: 싱글톤 캡슐화]
    // -------------------------------------------------------------------------
    // 외부에서 `Physics myPhysics;` 처럼 무분별하게 객체를 생성하는 행위를 금지함.
    Physics() = default;

public:
    // -------------------------------------------------------------------------
    // [전역 접근 통로: GetInstance]
    // -------------------------------------------------------------------------
    // 프로그램 전체에서 오직 이 함수를 통해서만 물리 시스템에 접근할 수 있음.
    // 사용법: Physics::GetInstance().UpdatePhysics();
    static Physics& GetInstance()
    {
        // 지역 정적 변수 특성을 이용한 쓰레드 세이프하고 매끄러운 지연 초기화(Lazy Initialization)
        static Physics instance;
        return instance;
    }

    // -------------------------------------------------------------------------
    // [메모리 안정성 보장: 생성 제약]
    // -------------------------------------------------------------------------
    ~Physics() = default;

    // 의도치 않게 주소를 복사하거나 대입하여 다중 인스턴스가 생기는 오류를 컴파일 레벨에서 차단
    Physics(const Physics&) = delete;
    Physics& operator=(const Physics&) = delete;

    // -------------------------------------------------------------------------
    // [외부 컴포넌트 통신 인터페이스]
    // -------------------------------------------------------------------------
    // 주의: 본 함수들의 실제 기계어 구현 본문은 상호 참조 해결을 위해 
    // 헤더가 아닌 cpp 파일(또는 main.cpp 하단 구현 바인딩 영역)에 분리 작성되어야 함.

    // BoxCollider 컴포넌트가 Start()될 때 호출하여 충돌 연산 대상 풀(Pool)에 추가함.
    void RegisterCollider(BoxCollider* collider);

    // BoxCollider 컴포넌트가 소멸자(~BoxCollider)를 탈 때 호출하여 연산 풀에서 안전하게 지움.
    void UnregisterCollider(BoxCollider* collider);

    // GameLoop.hpp 파이프라인 내부에서 매 프레임 1회 호출되어 전체 충돌 흐름을 갱신 및 트리거함.
    void UpdatePhysics();

private:
    // -------------------------------------------------------------------------
    // [기하학 내부 연산용 헬퍼]
    // -------------------------------------------------------------------------
    // 두 콜라이더의 월드 AABB 평면 좌표(minBound, maxBound)가 서로 교차 상태인지 판단하는 순수 수학 함수
    bool CheckAABB(BoxCollider* a, BoxCollider* b);
};